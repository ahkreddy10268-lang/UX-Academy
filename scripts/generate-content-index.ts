/**
 * Regenerates content/knowledge/_index.ts and content/sources/_index.ts from the
 * files on disk. Deterministic — safe to run any number of times.
 *   npm run content:index
 */
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = join(import.meta.dirname, "..");

function walk(dir: string): string[] {
  return readdirSync(dir)
    .flatMap((name) => {
      const full = join(dir, name);
      if (statSync(full).isDirectory()) return walk(full);
      return name.endsWith(".ts") && !name.startsWith("_") ? [full] : [];
    })
    .sort();
}

function writeIndex(dir: string, exportName: string, typeImport: string, flat: boolean) {
  const files = walk(join(root, dir));
  const imports = files.map((file, i) => {
    const rel = "./" + relative(join(root, dir), file).replace(/\.ts$/, "");
    return `import m${i} from "${rel}";`;
  });
  const list = files.map((_, i) => `m${i}`).join(",\n  ");
  const body = `/* AUTO-GENERATED by scripts/generate-content-index.ts — do not edit. */
${typeImport}
${imports.join("\n")}

export const ${exportName} = [
  ${flat ? list.split(",\n  ").map((m) => `...${m}`).join(",\n  ") : list}
];
`;
  writeFileSync(join(root, dir, "_index.ts"), body);
  console.log(`${dir}/_index.ts — ${files.length} files`);
}

writeIndex("content/knowledge", "rawEntries", `import type { KnowledgeEntryInput } from "../../lib/content/schema";`, false);
writeIndex("content/sources", "rawSources", `import type { Source } from "../../lib/content/schema";`, true);
