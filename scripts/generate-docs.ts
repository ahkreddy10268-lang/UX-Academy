/**
 * Generates the data-derived documentation from the content itself, so it can
 * never drift from what is actually in the academy:
 *   docs/KNOWLEDGE_TAXONOMY.md, docs/RESEARCH_SOURCES.md, docs/CONTENT_COVERAGE.md
 *   npm run docs:generate
 */
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { allQuestions, domains, entries, glossary, itemsForSubcategory, labs, libraryFormulas, sources, verification, comparisons, workshops, learningPaths } from "../lib/content";
import { domainCoverage, qualitySummary } from "../lib/content/coverage";
import { EVIDENCE_LABEL, STATUS_LABEL, TIER_LABEL, TYPE_LABEL } from "../lib/content/labels";
import { CONTENT_STATUSES } from "../lib/content/schema";

const docs = join(import.meta.dirname, "..", "docs");
const today = new Date().toISOString().slice(0, 10);
const header = (title: string, note: string) => `# ${title}\n\n> Generated by \`npm run docs:generate\` on ${today} from \`/content\`. Do not edit by hand.\n> ${note}\n\n`;

/* ---------------- Taxonomy ---------------- */
let tax = header("Knowledge taxonomy", "Status: ✅ published entry · ✏️ drafted/reviewed · ◻️ planned (no educational content yet).");
const totalItems = domains.reduce((s, d) => s + d.subcategories.reduce((t, sub) => t + itemsForSubcategory(d.id, sub.id).length, 0), 0);
tax += `${domains.length} domains · ${domains.reduce((s, d) => s + d.subcategories.length, 0)} subcategories · ${totalItems} topics.\n\n`;
domains.forEach((d, i) => {
  tax += `## ${i + 1}. ${d.title} (\`${d.id}\`)\n\n${d.description}\n\n`;
  for (const s of d.subcategories) {
    tax += `### ${s.title} (\`${s.id}\`)\n\n`;
    for (const it of itemsForSubcategory(d.id, s.id)) {
      const mark = it.entry ? (it.entry.status === "published" ? "✅" : "✏️") : "◻️";
      tax += `- ${mark} ${it.title} — *${TYPE_LABEL[it.type]}* · \`${it.slug}\`\n`;
    }
    tax += "\n";
  }
});
writeFileSync(join(docs, "KNOWLEDGE_TAXONOMY.md"), tax);

/* ---------------- Sources ---------------- */
const status = (id: string) => verification[id]?.status ?? "not machine-checked";
let src = header("Research source registry", "Machine verification: DOIs resolved via Crossref (title/year compared); URLs fetched by HTTP. `npm run sources:verify -- --all` refreshes.");
const counts: Record<string, number> = {};
sources.forEach((s) => (counts[status(s.id)] = (counts[status(s.id)] ?? 0) + 1));
src += `**${sources.length} sources.** ` + Object.entries(counts).map(([k, v]) => `${k}: ${v}`).join(" · ") + "\n\n";
src += `Awaiting verification (authoring claim): ${sources.filter((s) => s.verification === "awaiting-verification").map((s) => `\`${s.id}\``).join(", ") || "none"}.\n\n`;
src += "Fields per record (see `lib/content/schema.ts`): id, title, authors, organisation, container, publisher, year, volume, issue, pages, DOI, ISBN, URL, type, tier, topics, licence, access, verification, notes.\n\n";
for (const t of [1, 2, 3, 4]) {
  const list = sources.filter((s) => s.tier === t).sort((a, b) => a.id.localeCompare(b.id));
  src += `## ${TIER_LABEL[t]} (${list.length})\n\n| ID | Reference | Identifier | Access | Verification |\n|---|---|---|---|---|\n`;
  for (const s of list) {
    const who = s.authors.length ? (s.authors.length > 3 ? `${s.authors[0]} et al.` : s.authors.join(", ")) : s.organisation ?? "";
    const id = s.doi ? `doi:${s.doi}` : s.isbn ? `ISBN ${s.isbn}` : s.url ?? "—";
    src += `| \`${s.id}\` | ${who}${s.year ? ` (${s.year})` : ""}. *${s.title.replace(/\|/g, "/")}*${s.container ? `. ${s.container}` : ""} | ${id} | ${s.access} | ${status(s.id)}${verification[s.id]?.checkedAt ? ` (${verification[s.id].checkedAt})` : ""} |\n`;
  }
  src += "\n";
}
writeFileSync(join(docs, "RESEARCH_SOURCES.md"), src);

/* ---------------- Coverage ---------------- */
const cov = domainCoverage();
let c = header("Content coverage", "A topic is covered only when its entry is published and passes every quality gate (enforced by tests/content.test.ts).");
c += `| Measure | Count |\n|---|---|\n`;
for (const [k, v] of [
  ["Topics in taxonomy", cov.reduce((s, x) => s + x.total, 0)],
  ["Published entries", entries.filter((e) => e.status === "published").length],
  ["Formulas with calculators", libraryFormulas.length],
  ["Quiz questions", allQuestions.length],
  ["Exercises", entries.reduce((s, e) => s + e.exercises.length, 0)],
  ["Flashcards", entries.reduce((s, e) => s + e.flashcards.length, 0)],
  ["Labs", labs.length],
  ["Workshops", workshops.length],
  ["Comparisons", comparisons.length],
  ["Learning paths", learningPaths.length],
  ["Glossary terms", glossary.length],
  ["Sources", sources.length],
] as const)
  c += `| ${k} | ${v} |\n`;
c += `\n## By domain\n\n| Domain | ${CONTENT_STATUSES.map((s) => STATUS_LABEL[s]).join(" | ")} | Written |\n|---|${CONTENT_STATUSES.map(() => "---:").join("|")}|---:|\n`;
for (const d of cov) c += `| ${d.title} | ${CONTENT_STATUSES.map((s) => d.byStatus[s]).join(" | ")} | ${Math.round((d.published / d.total) * 100)}% |\n`;
c += `\n## Quality gate\n\n` + qualitySummary().map((q) => `- ${q.gate}: ${q.passing}/${q.total}`).join("\n") + "\n";
c += `\n## Published entries\n\n| Entry | Type | Evidence | Refs | Quiz | Exercises | Formula | Lab |\n|---|---|---|---:|---:|---:|---|---|\n`;
for (const e of entries)
  c += `| ${e.title} | ${TYPE_LABEL[e.primaryType]} | ${EVIDENCE_LABEL[e.evidence]} | ${e.references.length} | ${e.quiz.length} | ${e.exercises.length} | ${e.formulas.map((f) => f.calculator).join(", ") || "—"} | ${e.lab ?? "—"} |\n`;
writeFileSync(join(docs, "CONTENT_COVERAGE.md"), c);

console.log("docs/KNOWLEDGE_TAXONOMY.md, docs/RESEARCH_SOURCES.md, docs/CONTENT_COVERAGE.md written");
